package Module1.Lecture1;

// The class name must match the file name
public class HelloWorld {
    // public: can be accessed by other classes
    // static: belongs to the class itself; doesn't need an instance to be called
    // void: the function does not return anything
    // args: an array of command-line specified strings
    public static void main(String[] args) {
        System.out.println("Hello, world!");
    }
}